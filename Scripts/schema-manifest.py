#!/usr/bin/env python3
"""Generate/check the binary's expected schema; never modifies SQL migrations."""
import argparse
import hashlib
from pathlib import Path
import sys

root = Path(__file__).resolve().parent.parent
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
lines = ['// Generated by Scripts/schema-manifest.py; update with every forward migration.',
         'public enum ExpectedDatabaseSchema {', '    public static let migrations: Set<SchemaMigration> = [']
for namespace in ['world', 'runtime']:
    for path in sorted((root / 'Migrations' / namespace).glob('*.sql')):
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        lines.append(f'        .init(namespace: "{namespace}", version: "{path.name}", checksum: "{digest}"),')
lines += ['    ]', '}', '']
expected = '\n'.join(lines)
output = root / 'Sources/SquidraPostgres/ExpectedDatabaseSchema.swift'
if args.check:
    if not output.exists() or output.read_text() != expected:
        sys.exit('Expected database schema is stale; run python3 Scripts/schema-manifest.py')
else:
    output.write_text(expected)
