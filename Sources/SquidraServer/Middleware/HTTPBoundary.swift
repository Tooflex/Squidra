import Foundation
import Hummingbird
import SquidraProtocols

struct BoundaryContext: RequestContext {
    var coreContext: CoreRequestContextStorage
    var actorID: UUID?
    var requestID = UUID()
    init(source: Source) { coreContext = .init(source: source) }

    func requireActor(_ requestedActor: UUID) throws {
        guard actorID == requestedActor else { throw HTTPError(.forbidden) }
    }
}

/// Wrap the entire router, including unmatched routes. No unauthenticated data mode.
struct HTTPBoundary<Inner: HTTPResponder>: HTTPResponder where Inner.Context == BoundaryContext {
    let inner: Inner
    let configuration: BoundaryConfiguration
    private static var publicProbes: Set<String> { ["/health/live", "/health/ready", "/health", "/ready"] }

    func respond(to request: Request, context: BoundaryContext) async throws -> Response {
        var context = context
        // Always generated by this host; never trust a caller's correlation ID.
        context.requestID = UUID()
        let origin = request.headers[.origin]
        var response: Response
        do {
            guard request.headers[values: .origin].count <= 1,
                  origin == nil || origin == configuration.approvedOrigin else { throw HTTPError(.forbidden) }
            if request.method == .options {
                guard origin != nil,
                      let method = request.headers[.accessControlRequestMethod],
                      ["GET", "POST", "PUT", "PATCH", "DELETE"].contains(method) else { throw HTTPError(.forbidden) }
                let names = (request.headers[.accessControlRequestHeaders] ?? "").split(separator: ",")
                    .map { $0.trimmingCharacters(in: .whitespaces).lowercased() }
                guard names.allSatisfy({ ["authorization", "content-type", "x-actor-id", "last-event-id"].contains($0) }) else {
                    throw HTTPError(.forbidden)
                }
                response = Response(status: .noContent, headers: [
                    .accessControlAllowMethods: method,
                    .accessControlAllowHeaders: "Authorization, Content-Type, X-Actor-ID, Last-Event-ID",
                ])
            } else {
                let isProbe = request.method == .get && Self.publicProbes.contains(request.uri.path)
                if !isProbe {
                    guard request.headers[values: .authorization].count == 1,
                          configuration.authenticates(request.headers[.authorization]) else { throw HTTPError(.unauthorized) }
                    context.actorID = configuration.actorID
                    if let suppliedActor = request.headers[.init("X-Actor-ID")!] {
                        guard request.headers[values: .init("X-Actor-ID")!].count == 1,
                              UUID(uuidString: suppliedActor) == context.actorID else { throw HTTPError(.forbidden) }
                    }
                }
                response = try await boundedResponse(request, context: context)
                if !isProbe && response.status.code >= 400 { response = errorResponse(response.status, id: context.requestID) }
            }
        } catch let error as any HTTPResponseError {
            response = errorResponse(error.status, id: context.requestID)
        } catch is CancellationError {
            throw CancellationError()
        } catch {
            response = errorResponse(.internalServerError, id: context.requestID)
        }
        response.headers[.init("X-Request-ID")!] = context.requestID.uuidString
        response.headers[.cacheControl] = "no-store"
        response.headers[.accessControlAllowOrigin] = nil
        response.headers[.accessControlAllowCredentials] = nil
        response.headers[.accessControlExposeHeaders] = nil
        // No credentials/cookies: callers explicitly send their injected bearer credential.
        if origin == configuration.approvedOrigin {
            response.headers[.accessControlAllowOrigin] = configuration.approvedOrigin
            response.headers[.vary] = "Origin"
            response.headers[.accessControlExposeHeaders] = "X-Request-ID"
        }
        if response.status == .unauthorized { response.headers[.wwwAuthenticate] = "Bearer" }
        return response
    }

    private func boundedResponse(_ request: Request, context: BoundaryContext) async throws -> Response {
        try await withThrowingTaskGroup(of: Response.self) { group in
            group.addTask {
                var request = request
                if let length = request.headers[.contentLength] {
                    guard let size = Int(length), size >= 0 else { throw HTTPError(.badRequest) }
                    guard size <= configuration.maximumBodyBytes else { throw HTTPError(.contentTooLarge) }
                }
                // Inspect the stream even without Content-Length; restore it for the route.
                var buffer = ByteBuffer()
                for try await part in request.body {
                    guard part.readableBytes <= configuration.maximumBodyBytes - buffer.readableBytes else {
                        throw HTTPError(.contentTooLarge)
                    }
                    buffer.writeImmutableBuffer(part)
                }
                request.body = .init(buffer: buffer)
                return try await inner.respond(to: request, context: context)
            }
            group.addTask {
                try await Task.sleep(for: configuration.requestTimeout)
                throw HTTPError(.gatewayTimeout)
            }
            defer { group.cancelAll() }
            return try await group.next()!
        }
    }

    private func errorResponse(_ status: HTTPResponse.Status, id: UUID) -> Response {
        let fields: (String, String)
        switch status {
        case .unauthorized: fields = ("UNAUTHENTICATED", "Authentication is required.")
        case .forbidden: fields = ("POLICY_DENIED", "Access is denied.")
        case .notFound: fields = ("NOT_FOUND", "Resource not found.")
        case .badRequest: fields = ("VALIDATION_FAILED", "Invalid request.")
        case .contentTooLarge: fields = ("PAYLOAD_TOO_LARGE", "Request body exceeds the limit.")
        case .conflict: fields = ("CONFLICT", "Request conflicts with current state.")
        case .gone: fields = ("EXPIRED", "Retained data has expired.")
        case .serviceUnavailable: fields = ("UNAVAILABLE", "Service is unavailable.")
        case .gatewayTimeout: fields = ("TIMED_OUT", "Request deadline exceeded.")
        default: fields = ("INTERNAL_ERROR", "Request could not be completed.")
        }
        let envelope = APIErrorEnvelope(code: fields.0, message: fields.1, requestId: id)
        // Encoding this fixed, bounded string/UUID DTO cannot depend on user input.
        let data = try! JSONEncoder().encode(envelope)
        return Response(status: status, headers: [.contentType: "application/json"], body: .init(byteBuffer: .init(bytes: data)))
    }
}
